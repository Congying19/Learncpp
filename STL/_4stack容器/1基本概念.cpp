/*
	1. 基本概念

	栈结构：数据遵循后进先出（Last In First Out）原则，最后插入的元素最先被访问或删除。

	容器适配器：基于其他容器（如deque或list）封装而成，默认使用deque作为底层容器。

	操作受限：仅允许在栈顶（一端）进行插入和删除操作，不支持随机访问。
*/
/*
	2. 核心操作

	入栈（Push）：push(element)，将元素添加到栈顶。

	出栈（Pop）：pop()，移除栈顶元素（无返回值）。

	访问栈顶：top()，返回栈顶元素的引用（不删除）。

	判空：empty()，检查栈是否为空。

	大小：size()，返回栈中元素数量。
*/